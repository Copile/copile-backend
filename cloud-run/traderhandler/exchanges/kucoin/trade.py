from kucoin_futures.client import Trade, Market
from ..firestore_functions import get_user_keys, store_trade, get_user_margin


def send_trade(account_id, trade_id, plan_id, side, symbol, leverage, price):
    keys = get_user_keys(account_id, "kucoin")
    margin = get_user_margin(account_id, plan_id)

    # Connecting to Kucoin API
    client_trade = Trade(key=keys['api_key'], secret=keys['api_secret'], passphrase=keys['api_passphrase'],
                         is_sandbox=False, url='')
    client = Market(key=keys['api_key'], secret=keys['api_secret'], passphrase=keys['api_passphrase'], is_sandbox=False, url='')

    side = 'buy' if side == 'Buy' else 'sell'

    # Fixing symbol, because of exceptions
    if symbol == "BTCUSDT":
        symbol = "XBTUSDTM"
    else:
        symbol = f"{symbol}M"

    # Getting round precision for future use
    multiplier = client.get_contract_detail(symbol=symbol)['multiplier']
    min_qty = 1 * float(multiplier)
    precision = int(len(str(min_qty).split(".")[1]))

    # Calculation right lot size for trade size
    quantity = (round((float(margin) * int(leverage) / float(price)), precision)) / float(multiplier)

    # Placing Limit Order
    try:
        create_order = client_trade.create_limit_order(
            symbol=symbol,
            size=quantity,
            price=str(price),
            side=side,
            lever=str(int(leverage)),
            type='limit'
        )
        order_id = create_order['orderId']  # orderId generated by kucoin
        order_dict = {
            "trade_id": trade_id,
            "order_id": order_id,

            "symbol": symbol,
            "type": "LIMIT",
            "side": side,
            "quantity": quantity,
            "entry": price,
            "leverage": leverage,
            "margin": margin,
            "exchange": "bybit"
        }
        store_trade(account_id, order_dict)
        return f"**Successfully placed order! - {account_id} - {symbol}**"
    except Exception as error:
        print(error)
